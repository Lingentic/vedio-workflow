import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { Store } from '../lib/store.ts';
import { Media } from '../lib/media.ts';
import { Library } from '../lib/library.ts';
import { fixedNarrationDefinitions, fixedNarrationVisuals } from '../lib/fixed-narration-visuals.ts';
import { inside } from '../lib/paths.ts';

test('固定口播只接受已核对的节点和版本；未指定、错绑或丢失的画面保持空白', t => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'fixed-narration-'));
  const store = new Store(root), library = new Library(store, new Media(), () => false);
  t.after(() => { store.close(); assert.ok(inside(os.tmpdir(), root)); fs.rmSync(root, { recursive: true, force: true }); });
  const expected = fixedNarrationDefinitions.find(definition => definition.nodeId === 't1-b1')!;
  fs.writeFileSync(store.path('fixed.mp4'), 'fixture');
  const asset = { id: 'old', kind: 'presenter' as const, title: '旧价格画面', binding: 't1-b2', status: 'ready' as const, relativePath: 'fixed.mp4', duration: 1.6, sourceHash: expected.sha256, createdAt: new Date().toISOString() };
  store.putAsset(asset);
  let bindings = fixedNarrationVisuals(library);
  assert.equal(bindings.find(binding => binding.nodeId === 't1-b2')?.status, 'missing');
  assert.equal(bindings.find(binding => binding.nodeId === 't2-b2')?.status, 'unassigned');
  assert.equal(bindings.find(binding => binding.nodeId === 't1-b1')?.status, 'missing');
  store.putAsset({ ...asset, id: 'wrong-version', binding: 't1-b1', sourceHash: 'wrong' });
  assert.equal(fixedNarrationVisuals(library).find(binding => binding.nodeId === 't1-b1')?.assetId, null);
  store.putAsset({ ...asset, id: 'correct', binding: 't1-b1' });
  bindings = fixedNarrationVisuals(library);
  assert.equal(bindings.find(binding => binding.nodeId === 't1-b1')?.assetId, 'correct');
  assert.equal(bindings.find(binding => binding.nodeId === 't1-b1')?.duration, 1.6);
  assert.equal(bindings.find(binding => binding.nodeId === 't1-b3')?.placement, 'end');
  const price = fixedNarrationDefinitions.find(definition => definition.nodeId === 't1-b2')!;
  store.putAsset({ ...asset, id: 'price-bound', sourceHash: price.sha256, duration: 85 / 30 });
  const priceBinding = fixedNarrationVisuals(library).find(binding => binding.nodeId === 't1-b2')!;
  assert.equal(priceBinding.assetId, 'price-bound');
  assert.equal(priceBinding.duration, 85 / 30);
  assert.equal(priceBinding.placement, 'start');
  fs.rmSync(store.path('fixed.mp4'));
  assert.equal(fixedNarrationVisuals(library).find(binding => binding.nodeId === 't1-b1')?.assetId, null);
});
